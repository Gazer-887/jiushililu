// 做事纪律（plan51 F3 起源，K6 抽成共用模块）。
//
// 为什么必须是**纯函数 + 按实收工具表取舍**：这段原先内联在 `runAgent` 里，于是只有主代理吃得到，
// 而真正跑命令、写产物、交验证报告的是子代理（0.13.78 起它们才拿到 `run_command`）。
// 直接整段搬过去会重演 0.13.77 那个病 —— 纪律里写着 `update_todos` / `set_goal` / `spawn_agents`，
// 而子代理的工具表里没有这几件，模型第一轮就得花轮次自证矛盾。
//
// ⚠️ 静态性：同一份 `toolNames` 求出的字节必须相同（前缀缓存才不会被每轮打散）。
// 所以这里**不许**读时钟、随机数、工作区内容。

export interface ConductGap {
  /** 本会话没拿到的高危能力名 */
  capability: string
  /** 哪些可派子代理按自己的声明真能拿到它 */
  agents: string[]
}

export interface ConductInput {
  /** 本轮**实收**的工具名（不是"声明过的"，不是"注册表里有的"） */
  toolNames: string[]
  /**
   * 缺能力与其出口（主会话由 runner 按装配结果算出）。
   * 给了就把名字**写进规则里**，而不是让规则去指 `<self_view>` —— 子代理没有自视段，
   * 指着它就是一个悬空指针（模型会去派一个同样跑不了命令的 Agent）。
   */
  gaps?: ConductGap[]
}

/** 需要这些工具才成立的规则，缺工具就不该写这条（写了就是假承诺） */
const FIXED_BLOCKS: { lines: string[]; requires?: string[] }[] = [
  {
    lines: [
      '**能查就查，不许猜。** 凡是工具能确认的事实——工作区里有哪些文件、文件内容是什么、',
      '   网页上写了什么、命令输出是什么——**必须先调用工具核实，再回答**。',
      '   禁止凭推测、记忆或"应该差不多"直接作答。宁可多调一次工具，也不许给出没有依据的答案。'
    ]
  },
  { lines: ['**没核实过的事，不要用笃定的语气讲。** 不确定就说不确定，并说明需要查什么。'] },
  {
    lines: [
      '**能力不足时如实说，并给替代方案。** 若某件事要靠**本轮工具表里没有**的能力才能做成，',
      '   明确说明缺什么，再提出用现有工具能达到同样目的的替代做法。'
    ]
  },
  {
    // 拆成两条而不是合成一条：内置 executor 的 `tools:` 里通常**两件都没有**，
    // 合在一起就得整块丢掉，拆开才能"有一件就给一条"。
    requires: ['update_todos'],
    lines: [
      '**多步任务先列清单。** 需要三步以上的活儿，先用 update_todos 列出计划，',
      '   之后每完成一步就更新一次状态——用户据此知道进行到哪了。',
      '   单步小事不必列（清单是给"长活"用的，不是每句话都开一张表）。'
    ]
  },
  {
    requires: ['set_goal'],
    lines: [
      '用户交代了**跨轮次**的长期意图（"以后每次都要…""这个项目最终要…"）时，',
      '   用 set_goal 登记成目标——目标跨轮次存活、用户能暂停/完成它，与待办是两回事。'
    ]
  },
  {
    // 这条不依赖任何工具：它管的是"报告怎么写"，谁交付谁受约束
    lines: [
      '**自检与验收里，跳过 ≠ 通过。** 没能真正跑成的项要单独计成「跳过」，写清原因与补救路径；',
      '   汇总行不许写"全部通过"，退出码要能分三态（全过 0 / 有失败 1 / 有跳过 2）。',
      '   理由：一份"交付即验收"的自检若把未验证项算进通过，任何自动化流程都会把它当绿灯放行。'
    ]
  }
]

/**
 * 组装做事纪律。编号由**实际给出的条数**按位置计算 —— 取舍之后不许断号，
 * 否则正文里"见第 N 条"这类指代会静默失效。
 */
export function composeConductRules(input: ConductInput): string {
  const has = (name: string): boolean => input.toolNames.includes(name)
  const blocks: string[][] = FIXED_BLOCKS.filter((b) => !b.requires || b.requires.every(has)).map((b) => b.lines)

  if (has('spawn_agents')) {
    blocks.push([
      '**能并行的独立活派给子代理。** 有多个互不依赖的子任务（同时审几个文件、分别查几条线索）时，',
      '   用 spawn_agents 一次派出去并行跑，比一件件做快得多。',
      '   但子代理看不到你们的对话，任务书必须自包含；有先后依赖的活别派。'
    ])
  }

  // 出口只在**真有派发口**时才算数：没有 spawn_agents 却写"派给某某"，就是本模块要消灭的那类
  // 假承诺。调用方（runner）虽然已经这么筛过，但纯函数不该依赖调用方的自觉 —— 谁传谁负责。
  const providers = has('spawn_agents')
    ? (input.gaps ?? []).flatMap((g) => (g.capability === 'run_command' ? g.agents : []))
    : []
  blocks.push(
    has('run_command')
      ? [
          '**耗时的活转后台 —— 但"输出多"不等于"耗时长"。** 构建、起服务、下载这类真要跑几十秒以上的，',
          '   用 run_command 的 background=true 转后台，再用 check_command 查进度（前台只有 30 秒，硬等必然超时）。',
          '   反过来：**打印一大堆内容的命令（cat/tail 大文件、跑本地脚本刷日志）是毫秒级的** —— 直接前台跑，',
          '   **不要因为"它输出会很长"就转后台**：那会白多出好几轮（2026-09-13 真机实测：模型把一条毫秒级命令',
          // 这里不点 `kill_command` 的名：它**不随 `run_command` 自动补齐**（破坏性，要显式声明），
          // 点了就是一个工具表里没有的名字 —— 正是本模块要消灭的那类措辞。
          '   转后台后又去查进度、终止任务，一轮任务多烧了好几倍 token）。'
        ]
      : providers.length > 0
        ? [
            '**本轮没有命令执行能力**（工具表里没有 run_command）。需要跑构建、起服务、装依赖时：',
            `   用 spawn_agents 派给能干这事的子代理（${providers.join('、')}），别自己凭"应该能跑"下结论。`
          ]
        : [
            '**本轮没有命令执行能力**（工具表里没有 run_command，也没有可派发的子代理提供它）。',
            '   涉及"跑一遍才知道"的结论，如实说明**未能验证**，不许凭推测宣称已通过。'
          ]
  )

  return ['**做事纪律（必须遵守）**：', ...blocks.map((b, i) => `${i + 1}. ${b.join('\n')}`)].join('\n')
}
